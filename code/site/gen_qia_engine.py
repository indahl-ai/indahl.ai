#!/usr/bin/env python3
"""gen_qia_engine.py (16 Nov 2026): wraps the /qia "Check a run" page engine (public/qia/runcheck.js, the qia_check.py rules R01-R12 in JS)
as an ES module for the worker, byte for byte, so the MCP tools, the page and the pip package read records with one rule set.
The worker never sees `document`, so the page part of the file returns before it runs. Rerun after any change to runcheck.js;
tests/test_qia.mjs refuses a stale copy (it compares the embedded sha256)."""
import hashlib, os
H = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(H, '..', 'cloudflare-workers', 'heuremen-door', 'public', 'qia', 'runcheck.js')
src = open(SRC, encoding='utf-8').read(); sha = hashlib.sha256(src.encode()).hexdigest()
out = ('// GENERATED by gen_qia_engine.py from public/qia/runcheck.js (sha256 %s). Do not edit; edit runcheck.js and rerun.\n'
       'const module = { exports: {} }; const window = undefined;\n%s\nexport const ENGINE_SHA256 = %r;\nexport default module.exports;\n') % (sha, src, sha)
open(os.path.join(H, 'qia_engine.js'), 'w', encoding='utf-8').write(out); print('qia_engine.js', sha[:16])
